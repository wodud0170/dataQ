  AND COALESCE(t1.OBJ_OWNER,'') = COALESCE(t2.OBJ_OWNER,'')
  AND t1.TABLE_NM   = t2.TABLE_NM
  AND t1.INDEX_NM   = t2.INDEX_NM
  AND t1.COLUMN_POS = t2.COLUMN_POS
  AND (COALESCE(c1.CLCT_END_DT,'') < COALESCE(c2.CLCT_END_DT,'')
       OR (COALESCE(c1.CLCT_END_DT,'') = COALESCE(c2.CLCT_END_DT,'') AND t1.SEQ < t2.SEQ));

