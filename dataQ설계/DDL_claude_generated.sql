--   OBJ/ATTR 와 동일한 방식(DM_ID + 자연키 PK + UPSERT + soft-delete)으로 정리.
--
-- 자연키:
--   INDEX      — (DM_ID, OBJ_OWNER, TABLE_NM, INDEX_NM, COLUMN_POS)
--   CONSTRAINT — (DM_ID, OBJ_OWNER, TABLE_NM, CONSTRAINT_NM, COLUMN_POS)
--
